// Turns brand/site.src.html (the marketing site design) into the pieces the Next.js landing page uses:
//   frontend/src/components/marketing/landing.css       the design CSS, scoped under .mk
//   frontend/src/components/marketing/landing-html.ts   the page markup as a string
// Run:  node brand/make-landing.js     (behaviour lives in landing-behaviour.ts, ported by hand)
const fs = require("fs");
const path = require("path");

const src = fs.readFileSync(path.join(__dirname, "site.src.html"), "utf8");
const out = path.join(__dirname, "..", "frontend", "src", "components", "marketing");
fs.mkdirSync(out, { recursive: true });

const css = src.match(/<style>([\s\S]*?)<\/style>/)[1].replace(/\/\*[\s\S]*?\*\//g, "");
const body = src.slice(src.indexOf("</style>") + 8, src.indexOf("<script>"));

/* ---------- CSS scoping ---------- */
function splitTop(text) {
  // split into [prelude, block] pairs at top level
  const rules = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf("{", i);
    if (open < 0) break;
    let depth = 1, j = open + 1;
    while (j < text.length && depth) { if (text[j] === "{") depth++; else if (text[j] === "}") depth--; j++; }
    rules.push([text.slice(i, open).trim(), text.slice(open + 1, j - 1)]);
    i = j;
  }
  return rules;
}

function scopeSelector(sel) {
  sel = sel.trim();
  if (sel === ":root") return ".mk";
  if (sel === "html" || sel === "body" || sel === "html,body") return ".mk";
  if (sel === "*") return ".mk *";
  if (sel.startsWith("body.bn")) return sel.replace(/^body\.bn/, ".mk.bn");
  if (sel.startsWith(":root[data-theme=\"dark\"]")) return `:root[data-theme="dark"] .mk`;
  return ".mk " + sel;
}

function scope(text) {
  return splitTop(text)
    .map(([pre, block]) => {
      if (pre.startsWith("@media")) {
        if (pre.includes("prefers-color-scheme")) return ""; // theme follows data-theme only
        return `${pre}{${scope(block)}}`;
      }
      if (pre.startsWith("@keyframes")) return `${pre}{${block}}`;
      if (pre === "html" && block.includes("scroll-behavior")) return ""; // global; do not leak
      const selectors = pre.split(",").map(scopeSelector);
      return `${[...new Set(selectors)].join(",")}{${block}}`;
    })
    .filter(Boolean)
    .join("\n");
}

let scoped = scope(css);
scoped = scoped
  // fonts come from next/font variables, loaded by the brand layout
  .replace(/--display:[^;]+;/, '--display:var(--font-bricolage),"Segoe UI",system-ui,sans-serif;')
  .replace(/--body:[^;]+;/, '--body:var(--font-figtree),"Segoe UI",system-ui,sans-serif;')
  .replace(/--mono:[^;]+;/, '--mono:var(--font-jbmono),ui-monospace,Consolas,monospace;')
  .replace(/--bn:[^;]+;/, '--bn:var(--font-anek),"Noto Sans Bengali","Nirmala UI",sans-serif;')
  // the logos are <img> files now, not inline svg
  .replace(/\.nav \.lg svg/g, ".mk .nav .lg img")
  .replace(/footer svg\{/g, "footer img{")
  // body-level rules become .mk rules
  .replace(/\.mk\{margin:0;/, ".mk{margin:0;min-height:100vh;");
// the floating theme button is replaced by a React-free one wired in landing-behaviour
const themeFix = "\n.mk .themeb{display:block}\n";
fs.writeFileSync(path.join(out, "landing.css"), `/* Generated by brand/make-landing.js from brand/site.src.html. Do not edit by hand. */\n${scoped}${themeFix}`);

/* ---------- markup ---------- */
let html = body
  .replace(/\{\{logo-horizontal-reverse\}\}/g, '<img src="/brand/logo-horizontal-reverse.svg" alt="Eleventory" width="168" height="33">')
  .replace('<a class="si" href="#"', '<a class="si" href="/login"')
  .replace(/href="#cta"/g, 'href="/signup"')
  .replace('<a class="btn coral" href="#" data-i="n6">', '<a class="btn coral" href="/signup" data-i="n6">')
  .replace('<a href="#">Terms</a><a href="#">Privacy</a><a href="#">Help</a><a href="#">Contact</a>',
    '<a href="/legal/terms">Terms</a><a href="/legal/privacy">Privacy</a><a href="/help">Help</a>')
  .replace("DRAFT PRICES FOR THIS DESIGN. Real plans and amounts are set in the billing settings.",
    "DRAFT PRICES. The amounts shown here are placeholders until the plans are confirmed.")
  .replace(/<button class="themeb"[^>]*>[^<]*<\/button>/, '<button class="themeb" id="themeBtn" type="button">Dark / light</button>');

// wrap in the .mk root; id="top" target for the logo link
html = `<div class="mk" id="mk-root"><span id="top"></span>${html.trim()}</div>`;

const ts = `// Generated by brand/make-landing.js from brand/site.src.html. Do not edit by hand.\nexport const LANDING_HTML = ${JSON.stringify(html)};\n`;
fs.writeFileSync(path.join(out, "landing-html.ts"), ts);

/* ---------- behaviour ---------- */
let js = src.slice(src.indexOf("<script>") + 8, src.indexOf("</script>"));
js = js
  .replace("const $=(s,r=document)=>r.querySelector(s),$$=(s,r=document)=>[...r.querySelectorAll(s)];",
    () => "const $=(s,r=root)=>r.querySelector(s),$$=(s,r=root)=>[...r.querySelectorAll(s)];")
  .replace(/(^|[;{}\s])addEventListener\("(scroll|resize)"/g, '$1win("$2"')
  .replace('document.body.classList.toggle("bn",bn)', 'root.classList.toggle("bn",bn)')
  .replace(/\$\("#themeBtn"\)\.addEventListener\("click",.*\n?/, '$("#themeBtn").addEventListener("click",()=>opts.toggleTheme());\n')
  .replace("stepsEl.forEach(s=>io.observe(s))}", "stepsEl.forEach(s=>io.observe(s));cleanups.push(()=>io.disconnect())}");
const behaviour = `/* eslint-disable */
// @ts-nocheck
// Generated by brand/make-landing.js from the <script> in brand/site.src.html. Do not edit by hand.
// Wires the scroll story, tilt, journey, seller tabs, language switch and theme button to the landing markup.
export function initLanding(root: HTMLElement, opts: { toggleTheme: () => void }): () => void {
const cleanups = [];
const win = (type, fn, o) => { window.addEventListener(type, fn, o); cleanups.push(() => window.removeEventListener(type, fn, o)); };
${js}
return () => cleanups.forEach((fn) => fn());
}
`;
fs.writeFileSync(path.join(out, "landing-behaviour.ts"), behaviour);

console.log("landing.css", Math.round(scoped.length / 1024) + " KB;", "landing-html.ts", Math.round(ts.length / 1024) + " KB");
